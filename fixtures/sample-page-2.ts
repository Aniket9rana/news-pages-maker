/** Real page bodies are short; cut at a sentence so the fixture has realistic lengths per tier. */
function shorten(body: string, score: Score): string {
  const limit = { 5: 760, 4: 400, 3: 290, 2: 260, 1: 230 }[score];
  if (body.length <= limit) return body;
  const cut = body.lastIndexOf("।", limit);
  return cut > limit * 0.5 ? body.slice(0, cut + 1) : body.slice(0, limit);
}

function s(
  id: string,
  score: Score,
  headline: string,
  dateline: string,
  byline: string,
  body: string,
  imgs: Array<[number, number, number, string?, Scene?]> = [],
  extra: Partial<Story> = {},
): Story {
  return {
    id,
    dateline,
    headline,
    subhead: "",
    body: shorten(body, score),
    byline,
    category: "",
    images: imgs.map(([w, h, seed, cap, scene], i) => placeholderImage(`${id}-i${i}`, w, h, seed, cap ?? "", scene)),
    score,
    scoreSource: "default",
    scoreReason: "",
    ...extra,
  };
}

