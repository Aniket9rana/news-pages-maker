import type { Score, Story, StoryImage } from "@/lib/types";

export type Scene = "crowd" | "fire" | "police" | "building" | "road" | "field" | "stage";

const SCENE_HUE: Record<Scene, number> = { crowd: 215, fire: 18, police: 200, building: 35, road: 95, field: 110, stage: 285 };

function people(w: number, h: number, n: number, seed: number): string {
  let out = "";
  for (let i = 0; i < n; i++) {
    const x = w * (0.12 + (0.76 * (i + 0.5)) / n) + ((seed * (i + 3)) % 17) - 8;
    const r = h * (0.07 + (((seed + i * 5) % 5) / 5) * 0.03);
    const y = h * (0.52 + (((seed + i * 7) % 4) / 4) * 0.08);
    out += `<circle cx="${x}" cy="${y}" r="${r}" fill="hsl(25,35%,70%)"/><rect x="${x - r * 1.5}" y="${y + r}" width="${r * 3}" height="${h}" rx="${r}" fill="hsl(${(seed * 37 + i * 61) % 360},35%,32%)"/>`;
  }
  return out;
}

/** Placeholder photo: a simple tinted scene (stands in for an uploaded photo). */
export function placeholderImage(id: string, w: number, h: number, seed: number, caption = "", scene: Scene = "crowd"): StoryImage {
  const hue = (SCENE_HUE[scene] + seed * 7) % 360;
  let art = "";
  if (scene === "fire") {
    art = `<rect x="0" y="${h * 0.7}" width="${w}" height="${h * 0.3}" fill="hsl(20,15%,18%)"/>
<path d="M${w * 0.2} ${h * 0.75} Q${w * 0.27} ${h * 0.2} ${w * 0.34} ${h * 0.75} Z" fill="hsl(28,95%,55%)"/>
<path d="M${w * 0.34} ${h * 0.75} Q${w * 0.45} ${h * 0.05} ${w * 0.58} ${h * 0.75} Z" fill="hsl(14,90%,50%)"/>
<path d="M${w * 0.55} ${h * 0.75} Q${w * 0.65} ${h * 0.25} ${w * 0.78} ${h * 0.75} Z" fill="hsl(40,95%,58%)"/>`;
  } else if (scene === "building") {
    art = `<rect x="${w * 0.1}" y="${h * 0.25}" width="${w * 0.8}" height="${h * 0.65}" fill="hsl(${hue},25%,55%)"/>` +
      Array.from({ length: 12 }, (_, i) => `<rect x="${w * (0.16 + (i % 6) * 0.12)}" y="${h * (0.33 + Math.floor(i / 6) * 0.22)}" width="${w * 0.07}" height="${h * 0.13}" fill="hsl(50,60%,75%)"/>`).join("") + people(w, h, 3, seed);
  } else if (scene === "road") {
    art = `<polygon points="${w * 0.4},${h * 0.4} ${w * 0.6},${h * 0.4} ${w * 0.95},${h} ${w * 0.05},${h}" fill="hsl(220,8%,30%)"/><rect x="${w * 0.49}" y="${h * 0.45}" width="${w * 0.02}" height="${h * 0.5}" fill="hsl(50,80%,70%)"/>`;
  } else if (scene === "field") {
    art = `<rect x="0" y="${h * 0.55}" width="${w}" height="${h * 0.45}" fill="hsl(${hue},45%,32%)"/>` +
      Array.from({ length: 5 }, (_, i) => `<circle cx="${w * (0.12 + i * 0.19)}" cy="${h * 0.42}" r="${h * 0.16}" fill="hsl(${hue},50%,26%)"/><rect x="${w * (0.12 + i * 0.19) - 4}" y="${h * 0.42}" width="8" height="${h * 0.3}" fill="hsl(25,40%,25%)"/>`).join("");
  } else if (scene === "stage") {
    art = `<rect x="${w * 0.05}" y="${h * 0.62}" width="${w * 0.9}" height="${h * 0.1}" fill="hsl(0,0%,25%)"/>` + people(w, h, 6, seed);
  } else if (scene === "police") {
    art = `<rect x="${w * 0.08}" y="${h * 0.5}" width="${w * 0.84}" height="${h * 0.1}" fill="hsl(0,0%,82%)"/>` + people(w, h, 5, seed);
  } else {
    art = people(w, h, 4 + (seed % 3), seed);
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="hsl(${hue},55%,72%)"/><stop offset="1" stop-color="hsl(${(hue + 30) % 360},35%,38%)"/></linearGradient></defs><rect width="100%" height="100%" fill="url(#g)"/>${art}</svg>`;
  return { id, src: `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`, width: w, height: h, caption, focalX: 0.5, focalY: 0.45 };
}

